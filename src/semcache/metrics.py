"""Export cache stats to monitoring systems: Prometheus and OpenTelemetry.

Three ways in, from no dependencies to full integrations:

* :func:`prometheus_text` returns the Prometheus text format as a string. Serve it
  from any web framework at ``/metrics``; nothing to install.
* :class:`PrometheusCollector` plugs into ``prometheus_client``
  (``pip install "semcacher[prometheus]"``)::

      from prometheus_client import REGISTRY, start_http_server
      from semcache.metrics import PrometheusCollector

      REGISTRY.register(PrometheusCollector(cache))
      start_http_server(9100)

* :func:`register_opentelemetry` reports through the OpenTelemetry metrics API
  (``pip install "semcacher[otel]"``), so the numbers reach any OTel backend::

      from semcache.metrics import register_opentelemetry

      register_opentelemetry(cache)

Values are read from :attr:`SemanticCache.stats` each time they are collected, so
there is nothing to update by hand. With a shared store such as ``RedisStore`` each
process reports its own view of the shared totals, which include other processes'
counts as of their last flush.

Metrics (Prometheus names; OpenTelemetry uses dots, e.g. ``semcache.lookups``):

========================================  ========  ================================
``semcache_lookups_total``                counter   lookups
``semcache_hits_total{kind}``             counter   hits; ``kind`` = exact | semantic
``semcache_misses_total``                 counter   misses
``semcache_writes_total``                 counter   entries stored
``semcache_tokens_saved_total{type}``     counter   ``type`` = input | output
``semcache_cost_saved_usd_total``         counter   USD the hits avoided spending
``semcache_cost_spent_usd_total``         counter   USD the stored calls cost
``semcache_hit_ratio``                    gauge     hits / lookups
``semcache_entries``                      gauge     entries in the store
``semcache_model_*{model}``               both      the same, per model
========================================  ========  ================================
"""

from __future__ import annotations

from collections.abc import Iterable, Iterator
from dataclasses import dataclass
from typing import Any

from .cache import SemanticCache
from .stats import CacheStats, ModelStats

__all__ = ["Metric", "collect", "prometheus_text", "PrometheusCollector", "register_opentelemetry"]


@dataclass(frozen=True)
class Metric:
    """One metric with all its labelled samples, independent of any library."""

    name: str  # without prefix or _total suffix, e.g. "hits"
    kind: str  # "counter" or "gauge"
    description: str
    unit: str
    samples: tuple[tuple[dict[str, str], float], ...]


def _stats_metrics(stats: CacheStats) -> list[Metric]:
    def one(name: str, kind: str, desc: str, value: float, unit: str = "1") -> Metric:
        return Metric(name, kind, desc, unit, (({}, float(value)),))

    metrics = [
        one("lookups", "counter", "Cache lookups.", stats.lookups),
        Metric(
            "hits",
            "counter",
            "Lookups answered from the cache.",
            "1",
            (
                ({"kind": "exact"}, float(stats.exact_hits)),
                ({"kind": "semantic"}, float(stats.semantic_hits)),
            ),
        ),
        one("misses", "counter", "Lookups that found no cached answer.", stats.misses),
        one("writes", "counter", "Answers stored in the cache.", stats.writes),
        Metric(
            "tokens_saved",
            "counter",
            "Tokens not sent to or generated by the LLM thanks to cache hits.",
            "{token}",
            (
                ({"type": "input"}, float(stats.input_tokens_saved)),
                ({"type": "output"}, float(stats.output_tokens_saved)),
            ),
        ),
        one("cost_saved_usd", "counter", "USD the cache hits avoided.", stats.cost_saved, "USD"),
        one("cost_spent_usd", "counter", "USD the stored calls cost.", stats.cost_spent, "USD"),
        one("hit_ratio", "gauge", "Hits divided by lookups.", stats.hit_rate),
    ]

    models = sorted(stats.by_model.items())
    if models:

        def per_model(name: str, kind: str, desc: str, attr: str, unit: str = "1") -> Metric:
            samples = tuple(({"model": m}, float(getattr(s, attr))) for m, s in models)
            return Metric(name, kind, desc, unit, samples)

        metrics += [
            per_model("model_hits", "counter", "Cache hits per model.", "hits"),
            per_model("model_misses", "counter", "Cache misses per model.", "misses"),
            per_model(
                "model_cost_saved_usd", "counter", "USD saved per model.", "cost_saved", "USD"
            ),
            per_model(
                "model_cost_spent_usd", "counter", "USD spent per model.", "cost_spent", "USD"
            ),
            per_model("model_hit_ratio", "gauge", "Hit ratio per model.", "hit_rate"),
        ]
    return metrics


def collect(cache: SemanticCache, *, include_entries: bool = True) -> list[Metric]:
    """Read the cache's current stats as a list of :class:`Metric`.

    ``include_entries`` adds the ``entries`` gauge, which asks the store for its size
    (one round trip per namespace on ``RedisStore``).
    """
    metrics = _stats_metrics(cache.stats)
    if include_entries:
        metrics.append(
            Metric(
                "entries", "gauge", "Entries in the cache store.", "1", (({}, float(len(cache))),)
            )
        )
    return metrics


def _counter_name(prefix: str, metric: Metric) -> str:
    name = f"{prefix}_{metric.name}"
    return name + "_total" if metric.kind == "counter" else name


def _escape(value: str) -> str:
    return value.replace("\\", r"\\").replace("\n", r"\n").replace('"', r"\"")


def _format_value(value: float) -> str:
    return str(int(value)) if float(value).is_integer() else repr(float(value))


def prometheus_text(
    cache: SemanticCache, *, prefix: str = "semcache", include_entries: bool = True
) -> str:
    """The cache's metrics in the Prometheus text exposition format (version 0.0.4).

    Serve it with ``Content-Type: text/plain; version=0.0.4``. Needs no extra packages.
    """
    lines: list[str] = []
    for metric in collect(cache, include_entries=include_entries):
        name = _counter_name(prefix, metric)
        lines.append(f"# HELP {name} {metric.description}")
        lines.append(f"# TYPE {name} {metric.kind}")
        for labels, value in metric.samples:
            label_text = ",".join(f'{k}="{_escape(v)}"' for k, v in labels.items())
            suffix = f"{{{label_text}}}" if label_text else ""
            lines.append(f"{name}{suffix} {_format_value(value)}")
    return "\n".join(lines) + "\n"


class PrometheusCollector:
    """A ``prometheus_client`` collector that reads the cache's stats on every scrape.

    Register it once: ``prometheus_client.REGISTRY.register(PrometheusCollector(cache))``.
    """

    def __init__(
        self, cache: SemanticCache, *, prefix: str = "semcache", include_entries: bool = True
    ) -> None:
        try:
            from prometheus_client.core import CounterMetricFamily, GaugeMetricFamily
        except ImportError as exc:  # pragma: no cover - depends on optional extra
            raise ImportError(
                "PrometheusCollector needs prometheus_client: pip install 'semcacher[prometheus]'"
            ) from exc
        self._families = {"counter": CounterMetricFamily, "gauge": GaugeMetricFamily}
        self.cache = cache
        self.prefix = prefix
        self.include_entries = include_entries

    def collect(self) -> Iterator[Any]:
        for metric in collect(self.cache, include_entries=self.include_entries):
            labels = sorted({k for sample_labels, _ in metric.samples for k in sample_labels})
            family = self._families[metric.kind](
                f"{self.prefix}_{metric.name}", metric.description, labels=labels
            )
            for sample_labels, value in metric.samples:
                family.add_metric([sample_labels[k] for k in labels], value)
            yield family

    def describe(self) -> Iterable[Any]:
        # Returning the metrics lets the registry detect name clashes at register time.
        return self.collect()


def register_opentelemetry(
    cache: SemanticCache,
    meter: Any = None,
    *,
    prefix: str = "semcache",
    include_entries: bool = True,
) -> list[Any]:
    """Report the cache's metrics through OpenTelemetry observable instruments.

    Uses ``meter`` or, by default, ``opentelemetry.metrics.get_meter("semcache")``, so
    whatever ``MeterProvider`` the application configured receives them. Returns the
    created instruments.
    """
    try:
        from opentelemetry import metrics as otel_metrics
        from opentelemetry.metrics import Observation
    except ImportError as exc:  # pragma: no cover - depends on optional extra
        raise ImportError(
            "register_opentelemetry needs opentelemetry-api: pip install 'semcacher[otel]'"
        ) from exc

    meter = meter or otel_metrics.get_meter("semcache")

    def stats_callback(name: str) -> Any:
        def callback(options: Any) -> Iterator[Any]:
            for metric in _stats_metrics(cache.stats):
                if metric.name == name:
                    for labels, value in metric.samples:
                        yield Observation(value, labels)

        return callback

    def entries_callback(options: Any) -> Iterator[Any]:
        yield Observation(len(cache), {})

    # A template with one model, so the per-model instruments exist from the start.
    template = _stats_metrics(CacheStats(by_model={"_": ModelStats()}))
    specs = [(m, stats_callback(m.name)) for m in template]
    if include_entries:
        entries = Metric("entries", "gauge", "Entries in the cache store.", "1", ())
        specs.append((entries, entries_callback))

    instruments = []
    for metric, callback in specs:
        create = (
            meter.create_observable_counter
            if metric.kind == "counter"
            else meter.create_observable_gauge
        )
        instruments.append(
            create(
                f"{prefix}.{metric.name}",
                callbacks=[callback],
                unit=metric.unit,
                description=metric.description,
            )
        )
    return instruments
